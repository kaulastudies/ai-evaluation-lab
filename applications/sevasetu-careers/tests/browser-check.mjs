import { createRequire } from 'node:module';
import path from 'node:path';
import os from 'node:os';
const require = createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs');
const output = process.env.SEVASETU_SCREENSHOTS || fs.mkdtempSync(path.join(os.tmpdir(), 'sevasetu-qa-'));
fs.mkdirSync(output,{recursive:true});
const base = process.env.SEVASETU_BASE_URL || 'http://127.0.0.1:8090/';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--no-zygote','--single-process']});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.getByRole('heading',{name:'10 sample roles to review'}).waitFor();
 await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'View role: Warehouse Coordinator',exact:true}).click();
 await page.getByRole('button',{name:'Build CV for this role'}).click();
 await page.getByRole('dialog').waitFor();
 if(!(await page.locator('#cv-preview').innerText()).includes('Maintained stores and inventory'))throw Error('CV facts missing');
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download evidence',exact:true}).click()]);
 const downloadPath=await download.path();const receipt=JSON.parse(fs.readFileSync(downloadPath));
 if(receipt.claims.length!==5||receipt.cv_sha256.length!==64)throw Error('Bad receipt');
 const [cvDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download CV (.txt)',exact:true}).click()]);
 const cvBytes=fs.readFileSync(await cvDownload.path());
 if(require('node:crypto').createHash('sha256').update(cvBytes).digest('hex')!==receipt.cv_sha256)throw Error('CV download does not match receipt');
 await page.screenshot({path:path.join(output,'cv.png')});
 await page.emulateMedia({media:'print'}); await page.pdf({path:path.join(output,'print.pdf'),format:'A4'}); await page.emulateMedia({media:'screen'});
 await page.getByRole('button',{name:'Close CV preview'}).click();
 await page.getByRole('checkbox',{name:'Include deadline review queue'}).check();
 await page.getByRole('heading',{name:'11 sample roles to review'}).waitFor();
 await page.getByRole('button',{name:'Candidate profile',exact:true}).click();
 await page.getByLabel('Start with a sample').selectOption('1');
 await page.getByRole('button',{name:'Save facts & find roles'}).click();
 await page.getByRole('heading',{name:'Meera Singh (sample)',exact:true}).waitFor();
 await page.getByRole('button',{name:'View role: IT Support Associate',exact:true}).click();
 if(!(await page.locator('#detail').innerText()).includes('3/3 listed skills'))throw Error('IT profile not applied');
 await page.getByRole('button',{name:'How it works',exact:true}).click();
 await page.getByRole('button',{name:'Run demonstration checks'}).click();
 await page.locator('#check-results').filter({hasText:'PASS'}).waitFor();const checks=await page.locator('#check-results').innerText();if((checks.match(/PASS/g)||[]).length!==5)throw Error(checks);
 await page.getByRole('button',{name:'Find roles',exact:true}).click();
 await page.locator('#domain').selectOption('it');
 await page.getByRole('heading',{name:'2 sample roles to review'}).waitFor();
 await page.locator('#query').fill('<img src=x onerror=alert(1)>');
 if(await page.locator('img').count())throw Error('Unsafe query rendering');
 await page.locator('#query').fill('');await page.locator('#domain').selectOption('');
 const imported=JSON.parse(fs.readFileSync(new URL('../web/data/jobs.json',import.meta.url)));
 imported.jobs=imported.jobs.slice(0,1);imported.jobs[0].observed_at=new Date().toISOString();imported.jobs[0].posted_at=null;
 await page.locator('#jobs-file').setInputFiles({name:'test-vacancies.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))});
 await page.getByRole('heading',{name:'1 role to review',exact:true}).waitFor();
 if(!(await page.locator('#notice').innerText()).includes('Imported locally: 1 unique'))throw Error('Vacancy import failed');
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true});
 await mobile.goto(base);await mobile.getByRole('heading',{name:'10 sample roles to review'}).waitFor();
 if(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await mobile.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 const report={desktop:'PASS',cv_export:'PASS',receipt_export:'PASS',cv_hash_matches_download:true,print:'generated for visual review',review_queue:'PASS',profile_switch:'PASS',vacancy_import:'PASS',filters:'PASS',demo_checks:5,mobile_overflow:'none',page_errors:errors};
 fs.writeFileSync(path.join(output,'browser-checks.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report));
 await browser.close(); if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
